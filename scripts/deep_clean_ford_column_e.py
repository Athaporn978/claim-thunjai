    s = s.replace('น้ า', 'น้ำ').replace('น้ ำ', 'น้ำ').replace('น้า', 'น้ำ').replace('ดา+', 'ดำ+')
    s = s.replace('เคาะ - พน่ส ี', '').replace('เคาะ - พ่นสี', '').replace('เคาะ - พน่สี', '')

