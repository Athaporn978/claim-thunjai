def clean_entire_ford_sheet():
    excel_path = "/Users/arthur/Documents/Customer/H Tech/Labor Motor/Labor_Motor_Car_Brands.xlsx"
    wb = openpyxl.load_workbook(excel_path)
    ws = wb['FORD']

    cleaned_count = 0
    for r in range(2, ws.max_row + 1):
        old_val = ws.cell(row=r, column=5).value
        if old_val:
            new_val = deep_clean_thai(old_val)
            if new_val != old_val:
                ws.cell(row=r, column=5, value=new_val)
                cleaned_count += 1

    wb.save(excel_path)
    print(f"SUCCESS: Deep cleaned Column E across FORD sheet ({cleaned_count} rows fixed) at {excel_path}")

if __name__ == "__main__":
    clean_entire_ford_sheet()
