def clean_ford_sheet():
    excel_path = "/Users/arthur/Documents/Customer/H Tech/Labor Motor/Labor_Motor_Car_Brands.xlsx"
    wb = openpyxl.load_workbook(excel_path)
    ws = wb['FORD']

    fixed_count = 0
    for r in range(2, ws.max_row + 1):
        val = ws.cell(row=r, column=5).value
        if val:
            cleaned = perfect_thai_clean(val)
            if cleaned != val:
                ws.cell(row=r, column=5, value=cleaned)
                fixed_count += 1

    wb.save(excel_path)
    print(f"SUCCESS: Cleaned Column E across FORD sheet ({fixed_count} rows updated) at {excel_path}")

if __name__ == "__main__":
    clean_ford_sheet()
