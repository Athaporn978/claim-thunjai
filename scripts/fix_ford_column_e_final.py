def apply_fixes(text: str) -> str:
    if not text:
        return text
    for wrong, right in MASTER_FIXES:
        text = text.replace(wrong, right)
    # Remove double spaces
    text = re.sub(r'  +', ' ', text).strip()
    return text

wb = openpyxl.load_workbook(EXCEL_PATH)
ws = wb['FORD']

fixed_rows = []
for r in range(2, ws.max_row + 1):
    cell = ws.cell(r, 5)
    original = cell.value
    if not original:
        continue
    fixed = apply_fixes(original)
    if fixed != original:
        cell.value = fixed
        fixed_rows.append((r, original, fixed))

print(f'Fixed {len(fixed_rows)} rows:')
for r, orig, fixed in fixed_rows:
    print(f'  Row {r:3}: {repr(orig)}')
    print(f'         → {repr(fixed)}')
    print()

wb.save(EXCEL_PATH)
print(f'\nSaved. Total fixed: {len(fixed_rows)} rows.')

